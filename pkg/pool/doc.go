// Package tcp 提供按容量分级的并发安全字节缓冲池。
//
// 典型用法是为 WAL 或 SSTable 预先声明若干常用容量，通过 TieredPool.Get
// 获取指定长度的缓冲，并在数据不再使用后调用 TieredPool.Put。Get 返回值的长度
// 等于请求大小，容量则来自第一个足够大的桶；超过最大桶的请求会直接分配且不复用。
//
// 边界条件：容量列表不能为空，必须严格递增且全部为正数；Get 的 size 不能为负数。
// Put 只接收容量与某个桶完全相同的切片，外来容量会被丢弃。放回缓冲后，调用者不得
// 再读写该切片，也不能依赖下一次 Get 得到清零后的内容。
